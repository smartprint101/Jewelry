/* ----------------------------- হেল্পার ফাংশন ----------------------------- */

export function getProduct(slug: string): Product | undefined {
  return products.find((product) => product.slug === slug);
}

export function getProductsByCategory(category: CategorySlug): Product[] {
  return products.filter((product) => product.category === category);
}

export function getProductsByCollection(collection: CollectionSlug): Product[] {
  return products.filter((product) => product.collections.includes(collection));
}

export function getProductsByMaterial(material: MaterialSlug): Product[] {
  return products.filter((product) => product.materials.includes(material));
}

export function getRelatedProducts(product: Product, limit = 8): Product[] {
  const sameCategory = products.filter(
    (item) => item.slug !== product.slug && item.category === product.category,
  );
  const sameMaterial = products.filter(
    (item) =>
      item.slug !== product.slug &&
      item.category !== product.category &&
      item.materials.some((material) => product.materials.includes(material)),
  );
  return [...sameCategory, ...sameMaterial].slice(0, limit);
}

export function getFeaturedProducts(limit = 8): Product[] {
  return products.filter((product) => product.featured).slice(0, limit);
}

export function countByCategory(category: CategorySlug): number {
  return products.filter((product) => product.category === category).length;
}

export function countByMaterial(material: MaterialSlug): number {
  return products.filter((product) => product.materials.includes(material)).length;
}

/** অফার পেজ: সবচেয়ে বেশি ছাড়ের পণ্য */
export function getDiscountedProducts(minPercent = 15): Product[] {
  return products.filter((product) => {
    if (!product.oldPrice) return false;
    const percent = ((product.oldPrice - product.price) / product.oldPrice) * 100;
    return percent >= minPercent;
  });
}
